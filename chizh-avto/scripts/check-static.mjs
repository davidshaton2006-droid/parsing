import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const js=await readFile(new URL('../src/main.jsx',import.meta.url),'utf8');
const css=await readFile(new URL('../src/style.css',import.meta.url),'utf8');
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const catalog=await readFile(new URL('../src/data/catalog.js',import.meta.url),'utf8');
for(const name of ['ServicesPage','ProjectsPage','PricesPage','ContactsPage','OffersPage','AboutPage','VideoBlock','ServiceSelector','ProjectsStrip'])assert(js.includes('function '+name+'('),name+' missing');
for(const fragment of ['tel:', 'mailto:', 'navigator.clipboard', 'onSubmit={send}', 'setFilter', 'setSelected', 'setOpen', 'scrollPrev()', 'scrollNext()', 'aria-pressed', 'aria-expanded', 'onChange', 'onClick'])assert(js.includes(fragment),fragment+' missing');
assert(js.includes('video-fallback'),'Video fallback missing');
assert(js.includes('function verifiedOfficialService('),'Unverified service URL fallback missing');
assert(!css.includes('scroll-progress'),'No decorative progress bar');
assert(!css.includes('marquee'),'No decorative ticker');
assert(css.includes('prefers-reduced-motion'),'Reduced motion missing');
assert(html.includes('<noscript>'),'No-JS fallback missing');
assert(catalog.includes('chizhavto.ru/upload/'),'Original photos missing');
assert(!catalog.includes('unsplash.com')&&!catalog.includes('pexels.com'),'Stock photos forbidden');
console.log('Static checks passed.');
