import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const js=await readFile(new URL('../src/main.jsx',import.meta.url),'utf8');
const css=await readFile(new URL('../src/style.css',import.meta.url),'utf8');
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const catalog=await readFile(new URL('../src/data/catalog.js',import.meta.url),'utf8');
for(const name of ['ServicesPage','ProjectsPage','PricesPage','ContactsPage','OffersPage','AboutPage','VideoBlock','ServiceSelector','ProjectsStrip'])assert(js.includes('function '+name+'('),name+' is missing');
for(const fragment of ['tel:', 'mailto:', 'navigator.clipboard', 'onSubmit={send}', 'setFilter', 'setSelected', 'setOpen', 'scrollPrev()', 'scrollNext()', 'aria-pressed', 'aria-expanded', 'onChange', 'onClick'])assert(js.includes(fragment),fragment+' missing');
assert(js.includes('video-fallback'),'YouTube playback fallback missing');
assert(js.includes('function verifiedOfficialService('),'service links must avoid unverified deep URLs');
assert(!css.includes('scroll-progress'),'decorative progress bar must not return');
assert(!css.includes('marquee'),'decorative ticker must not return');
assert(css.includes('prefers-reduced-motion'),'reduced motion support missing');
assert(html.includes('<noscript>'),'no-JS fallback missing');
assert(catalog.includes('chizhavto.ru/upload/'),'company-only photos missing');
assert(!catalog.includes('unsplash.com'),'unapproved stock images must not be used');
assert(!catalog.includes('pexels.com'),'unapproved stock images must not be used');
console.log('Static production checks passed.');
